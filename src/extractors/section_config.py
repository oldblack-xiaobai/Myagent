# ---- 贷款类账户 Prompt（跳过结清/销户）----
_LOAN_PROMPT = """这是一份征信报告的"信贷交易明细 - {sub_name}"部分{maybe_multi_page}。

【逐笔提取】
对每个账户，提取：管理机构、担保方式、开立日期、到期日期、借款金额、余额、账户状态、五级分类

【日期字段注意】
- 开立日期和到期日期都是 4 位年份格式（如 2022.03.28）
- 请仔细区分形近数字：2 和 3、6 和 8、0 和 9、1 和 7

【待复核标记】
对以下字段：开立日期、到期日期、借款金额、余额，
如果你对读数**不太确定**（模糊、被遮挡、数字难辨），
在该字段后额外输出一个 `<字段名>_待复核` 字段，值为 true。

【还款记录表格结构】
还款记录表格的表头是 1 到 12 月份（横向）。
每个月份下有上下两行数据：
- 第 1 行：状态符号，取值 N/C/A/1-7/D/G/Z/*/#
- 第 2 行：该月的逾期金额（数字，0 表示无逾期，非 0 表示该月有逾期金额）

【还款记录返回规则】
如果出现以下任一情况，返回该账户的**整个还款记录表**：
- 符号行出现 N/C/A/* 之外的符号（如 1-7、D、G、Z、#）
- 金额行出现非 0 数字

如果所有符号都在 {{N, C, A, *}} 内，且所有金额都是 0 或空，则不返回"还款记录"字段。

【跳过规则】
账户状态是"结清"、"提前结清"或"销户"，且五级分类为"正常"或空 → 跳过该账户。

按以下 JSON 输出，不要任何其他文字：
{{"{sub_name}": [{{"管理机构": "", "担保方式": "", "开立日期": "", "到期日期": "", "借款金额": "", "余额": "", "账户状态": "", "五级分类": ""}}]}}"""


